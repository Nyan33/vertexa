"""Generates src/gfx/icons.h from the Phosphor icon CSS (codepoints).

Usage: python tools/gen_icons.py
Add an icon: put (ENUM_NAME, "phosphor-name") into ICONS and re-run.
"""
import re
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CSS = ROOT / "assets" / "icons" / "phosphor-regular.css"
OUT = ROOT / "src" / "gfx" / "icons.h"

ICONS = [
    # tools
    ("SELECT", "cursor"), ("TRANSFORM", "bounding-box"), ("LASSO", "lasso"),
    ("PEN", "pen-nib"), ("TEXT", "text-t"), ("LINE", "line-segment"), ("RECT", "rectangle"),
    ("PENCIL", "pencil-simple"), ("BRUSH", "paint-brush"), ("ERASER", "eraser"), ("BUCKET", "paint-bucket"),
    ("EYEDROPPER", "eyedropper"), ("BONE", "bone"), ("HAND", "hand"), ("ZOOM", "magnifying-glass"),
    # timeline
    ("PLAY", "play"), ("PAUSE", "pause"), ("SKIP_BACK", "skip-back"), ("SKIP_FWD", "skip-forward"),
    ("STEP_BACK", "caret-left"), ("STEP_FWD", "caret-right"), ("LOOP", "repeat"), ("ONION", "copy"),
    ("PLUS", "plus"), ("TRASH", "trash"), ("CARET_DOWN", "caret-down"), ("CARET_RIGHT", "caret-right"),
    ("EYE", "eye"), ("EYE_OFF", "eye-slash"), ("LOCK", "lock"), ("UNLOCK", "lock-open"),
    # layer types
    ("VECTOR", "bezier-curve"), ("RASTER", "image-square"), ("CAMERA", "camera"), ("AUDIO", "waveform"),
    ("FOLDER", "folder-simple"), ("MASK", "selection-background"), ("GUIDE", "path"), ("REFERENCE", "cube"),
    # misc
    ("CHECK", "check"), ("UNDO", "arrow-counter-clockwise"), ("REDO", "arrow-clockwise"), ("GEAR", "gear"),
    ("FILM", "film-strip"), ("STACK", "stack-simple"),
    # editing
    ("TRIM", "scissors"), ("OVAL", "circle"), ("SYMBOL", "shapes"), ("SAVE", "floppy-disk"), ("OPEN", "folder-open"),
    ("EXPORT", "export"), ("IMPORT", "download-simple"), ("ENTER", "sign-in"), ("BREAK", "intersect"),
    # settings
    ("SLIDERS", "sliders-horizontal"), ("CPU", "cpu"), ("KEYBOARD", "keyboard"), ("PALETTE", "palette"),
    ("SEARCH", "magnifying-glass"),
]


def main():
    css = CSS.read_text(encoding="utf-8")
    cps = dict(re.findall(r"\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*\"\\([0-9a-f]+)\"", css))
    lines = [
        "// Generated by tools/gen_icons.py from the Phosphor icon set (MIT). Do not edit by hand.",
        "#pragma once",
        "",
        "typedef enum {",
    ]
    lines += [f"    IC_{name}," for name, _ in ICONS]
    lines += ["    IC_COUNT", "} IconId;", "", "static const int ICON_CODEPOINTS[IC_COUNT] = {"]
    for name, ph in ICONS:
        if ph not in cps:
            raise SystemExit(f"missing icon: {ph}")
        lines.append(f"    0x{cps[ph]},  // {ph}")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(ICONS)} icons)")


if __name__ == "__main__":
    main()
